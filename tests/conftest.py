REPO_ROOT = Path(__file__).resolve().parents[1]
HOME = Path(os.path.expanduser("~"))


def _resolve_plexos_root() -> Optional[Path]:
    """Search order for the plexos test fixture directory.

    1. GAT_PLEXOS_FIXTURE env var (CI sets this)
    2. tests/fixtures/plexos/ (committed small fixture, if present)
    3. ~/.gat-test-data/plexos/ (legacy convention)
    4. example_data/plexos/ (in-repo full dataset for local dev)
    """
    candidates = []
    env = os.environ.get("GAT_PLEXOS_FIXTURE")
    if env:
        candidates.append(Path(env))
    candidates.extend([
        REPO_ROOT / "tests" / "fixtures" / "plexos",
        HOME / ".gat-test-data" / "plexos",
        REPO_ROOT / "example_data" / "plexos",
    ])
    for p in candidates:
        if p.is_dir() and any(p.glob("*.h5")):
            return p
    return None


def _resolve_plexos_zip_root() -> Optional[Path]:
    """Search order for a native PLEXOS Solution.zip fixture, used to test
    the plexos2duckdb-backed PlexosDuckDBSystem/PlexosDuckDBSimulation
    (distinct from the h5plexos-converted .h5 fixture above)."""
    candidates = []
    env = os.environ.get("GAT_PLEXOS_ZIP_FIXTURE")
    if env:
        candidates.append(Path(env))
    candidates.extend([
        REPO_ROOT / "tests" / "fixtures" / "plexos_zip",
        HOME / ".gat-test-data" / "plexos_zip",
        REPO_ROOT / "example_data" / "plexos_zip",
    ])
    for p in candidates:
        if p.is_dir() and any(p.glob("*.zip")):
            return p
        if p.is_file() and p.suffix.lower() == ".zip":
            return p
    return None


