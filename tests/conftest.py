def _resolve_sienna_versioned_root(version: str) -> Optional[Path]:
    """Search order for native SiennaScenario fixtures generated by docker/sienna/."""
    env = os.environ.get(f"GAT_SIENNA_V{version.upper().lstrip('V')}_FIXTURE")
    candidates = []
    if env:
        candidates.append(Path(env))
    candidates.append(REPO_ROOT / "example_data" / "sienna" / version)
    for p in candidates:
        if (p / "sys.json").is_file() and (p / "simulation_store.h5").is_file():
            return p
    return None


