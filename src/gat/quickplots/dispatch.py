def facet_area_dispatch_generic(dispatch, plot_func, palette=None, backend=None):

    areas = dispatch.columns.get_level_values(level='Area').unique()
    technologies = dispatch.columns.get_level_values(level='Technology').unique()

    tech_patches = prepare_tech_legend(technologies)
    num_areas = len(areas)

    grid_size = math.ceil(math.sqrt(num_areas))

    num_rows = math.floor(num_areas/grid_size)

    fig, axs = plt.subplots(grid_size, grid_size, figsize=(grid_size*2.0, grid_size*2.0), sharex=False, sharey=False, dpi=grid_size*100)

    axs = trim_axs(axs, num_areas-1)

    if num_areas > 1:
        axs_flat = axs.reshape(-1)[0:num_areas-1]
    else:
        axs_flat = [axs]

    for i, ax in enumerate(axs_flat):

        try:
            ax.spines[['right', 'top', 'bottom']].set_visible(False)
            plot_func(dispatch[areas[i]], ax=ax, palette=palette, backend=backend)
            ax.set_title("{}".format(areas[i]))
            ax.get_legend().remove()


            if i < num_areas - grid_size:
                ax.set_xlabel(None)
                ax.set_xticks([])

            # put ylabel in middle row left column
            if i % grid_size != 0:
                ax.set_ylabel(None)
        except Exception as e:
            logger.warning(f"Failed to plot for Area {areas[i]}")
            logger.warning(e)

    fig.set_size_inches(grid_size*5, num_rows*5)
    axs_flat[grid_size-1].legend(handles=tech_patches, loc='upper right', bbox_to_anchor=[1.6, 1.05])
    return fig, axs




