# assumes a frame with generation and demand columns (no multi-index)
def plot_dispatch_stack_bar(df, include_net_load=False, include_total_load=False, ax=None,
                            palette=None, backend=None, **kwargs):

    """
    Plots a bar chart of the Dispatch Stack dataframe

    expects a dataframe with columns of standard technology types (Wind, PV, etc.)

    y - axis: Total Generation and Demand* in TWh
    x - axis: The index of the dataframe. (examples: Months of the year, Year, ISOs, Balancing Areas)

    * Plots Demand if available
    """

    #Convert to TWh
    df_tw = df/MW_to_TW

    drop_cols = [col for col in config.load_columns if col in df_tw.columns]
    df_tw_stack = df_tw.drop(columns=drop_cols)

    horizontal = kwargs.pop('kind', 'bar') == 'barh'
    title = kwargs.pop("title", "Dispatch Stack")

    if ax is not None:
        kwargs['ax'] = ax

    result = plot_stacked_component_bar(
        df_tw_stack, horizontal=horizontal,
        palette=palette, backend=backend, **kwargs,
    )

    # Post-render formatting — use backend helpers when available
    from .backends import get_backend
    be = get_backend(backend)
    be.set_title(result, title)

    if not horizontal:
        be.set_ylabel(result, "Generation and Demand (TWh)")
    else:
        be.set_xlabel(result, "Generation and Demand (TWh)")

    return result


# expects a dataframe with generation technologies and demand as columns and timestamps as index
def plot_stacked_area_window(df, ax=None, include_net_load=False, include_total_load=False,
                             palette=None, backend=None, **kwargs):

    """
        Plots a stacked area chart of the various technology types.

        Generally reserved for plotting raw time windows of dataframes (no monthly or annual aggregates)
        Called by the plot_peak_demand_window() and plot_min_demand_window().

        x-axis: Dataframe index, usually timestamps
        y-axis: Power by Dispatch Technology in GW, (Wind, PV, etc)

    """

    if ax is not None:
        kwargs['ax'] = ax

    df_gw = df/MW_to_GW

    result = plot_stacked_component_area(df_gw,
                                linewidth=0,
                                include_total_load=include_total_load,
                                include_net_load=include_net_load,
                                palette=palette,
                                backend=backend,
                                **kwargs)

    return result

# expects a dataframe with generation technologies and demand as columns and timestamps as index
def plot_peak_demand_window(df, window_delta=3, ax=None, return_frame=False,
                            palette=None, backend=None, **kwargs):


    """
        Plots the stacked area chart for the peak demand window.
        Finds the index of the max demand and calls the plot_stacked_area() method

        Annotates the point of peak demand.

        x-axis: Dataframe index, usually timestamps
        y-axis: Power by Dispatch Technology in GW, (Wind, PV, etc)

    """

    if ax == None:
        ax = plt.axes()

    dfg = df.T.groupby( level='Technology').sum().T

    delta = pd.Timedelta(days=window_delta)

    idx_max = dfg[config.total_load_alias].idxmax()

    dfg_window = dfg.loc[idx_max.round('D')-delta:idx_max.round('D')+delta:]

    max_demand_val = dfg_window[config.total_load_alias].loc[idx_max]/MW_to_GW
    max_dispatch_val = dfg_window[[col for col in dfg.columns if col not in config.load_columns]].sum(axis=1).max()/MW_to_GW

    max_y = max(max_demand_val, max_dispatch_val)

    chart = plot_stacked_area_window(dfg_window, ax=ax, include_total_load=True,
                                     palette=palette, backend=backend, **kwargs)

    # Post-render formatting via backend helpers
    from .backends import get_backend
    be = get_backend(backend)
    annotate_timestamp = idx_max - pd.Timedelta(days=2)
    be.add_annotation(chart, f'Peak Demand: \n{max_demand_val:.2f} GW',
                      xy=(idx_max, max_demand_val),
                      xytext=(annotate_timestamp, max_y*1.1))
    be.set_title(chart, "Period of Peak Demand")
    be.set_ylim(chart, 0, max_y*1.3)
    be.set_xlim(chart, idx_max.round('D')-delta, idx_max.round('D')+delta)
    if return_frame:
        return chart, dfg_window
    else:
        return chart


