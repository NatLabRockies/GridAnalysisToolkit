def add_line(df,var,ax,style):
    if var in df.columns:
        xmin = [i-0.25 for i in range(len(df.index))]
        xmax = [i+0.25 for i in range(len(df.index))]
    ax.hlines(y=df[var].values, color='Black', linestyle=style, xmin=xmin, xmax=xmax, label=var)


def make_facet_axes(num_plots, **kwargs):
    grid_size = math.ceil(math.sqrt(num_plots))

    fig, axs = plt.subplots(grid_size, grid_size, **kwargs)

