def plot_dispatch_window(dispatch, timestamp, window_delta=3, annotate=True, annotate_text="", return_frame=False, ax=None, format_ticks=True,
                         palette=None, backend=None, **kwargs):

    # Let's assume we are always annotating demand.

    delta = pd.Timedelta(days=window_delta)
    dfg = dispatch.T.groupby(level='Technology').sum().T

    dfg_window = dfg.loc[timestamp.date()-delta:timestamp.date()+delta]

    if ax is not None:
        kwargs['ax'] = ax

    chart = plot_stacked_area_window(dfg_window, palette=palette, backend=backend, **kwargs)

    from .backends import get_backend
    be = get_backend(backend)

    # Tick formatting — only for matplotlib backend
    if format_ticks and be.name == "static":
        chart.xaxis.set_major_locator(mdates.DayLocator())
        chart.xaxis.set_major_formatter(mdates.DateFormatter('%b-%d\n%Y'))
        chart.xaxis.set_minor_locator(mdates.HourLocator(byhour=[6,12,18]))
        chart.xaxis.set_minor_formatter(mdates.DateFormatter(''))

        labels = chart.get_xticklabels()
        chart.set_xticklabels(labels, rotation=0, ha='center')
        chart.grid(visible=True,which='both', axis='x' ,alpha=0.2)

    # scale the frame
    max_demand_val = dfg_window[config.total_load_alias].max()/MW_to_GW
    max_dispatch_val = dfg_window[[col for col in dfg_window.columns if col not in config.load_columns]].max(axis=1).max()/MW_to_GW
    max_y = max(max_demand_val, max_dispatch_val)

    # annotate
    if annotate:
        annotate_loc = timestamp - pd.Timedelta(days=2)
        demand_val = dfg_window.loc[timestamp][config.total_load_alias]/MW_to_GW
        be.add_annotation(chart, annotate_text,
                          xy=(timestamp, demand_val),
                          xytext=(annotate_loc, max_y*1.3))

    be.set_xlim(chart, dfg_window.index.min(), dfg_window.index.max())
    if return_frame:
        return chart, dfg_window
    else:
        return chart

def facet_dispatch_windows(dispatch, timestamps:list, titles:list, window_delta=3, return_frame=False,
                           palette=None, backend=None, **kwargs):
    """
        takes in a dispatch dataframe and a list of timestamps,
        and returns a facet plot of those timestamps

    """
    num_plots = len(timestamps)
    fig, axs = make_facet_axes(len(timestamps), figsize=(num_plots*window_delta*2, num_plots*2), **kwargs)
    num_rows, num_cols = fig.axes[0].get_subplotspec().get_gridspec().get_geometry()

    unique_tech = dispatch.columns.get_level_values(level='Technology').unique()
    patches = prepare_tech_legend(unique_tech)

    axs=axs.reshape(-1)[0:num_plots]
    frames = []
    for i, time in enumerate(timestamps):

        ax = axs[i]
        if len(titles)>=i:
            title = titles[i]
            ax.set_title(title)

        if return_frame:
            ax, df = plot_dispatch_window(dispatch, time, window_delta, ax=ax, annotate=False,
                                          return_frame=return_frame, format_ticks=False,
                                          palette=palette, backend=backend)
            frames.append(df)
        else:
            ax = plot_dispatch_window(dispatch, time, window_delta, ax=ax, annotate=False,
                                      return_frame=return_frame, format_ticks=False,
                                      palette=palette, backend=backend)
        ax.get_legend().remove()
        if i == num_cols - 1:

            ax.legend(handles=patches, bbox_to_anchor=[1,1])
    if return_frame:
        df = pd.concat(frames)
        return fig, axs, df
    else:
        return fig, axs


