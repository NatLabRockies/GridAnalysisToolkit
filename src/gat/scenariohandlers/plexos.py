    def set_area_map(self, area_map: str ) -> None:
        """
        Sets the load->area and generator->area mapping based on available relations in the h5 dataset.

        :param area_map: 'zone' or 'region'

        """

        if area_map.lower() == 'zone':
            self._gen_area_map = get_h5_gen_zone_map(self._template_file)
            self._load_area_map = get_h5_region_zone_map(self._template_file)
